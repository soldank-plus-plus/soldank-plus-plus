struct MovementCheckpoint
{
    unsigned int tick;
    glm::vec2 displacement;
    glm::vec2 velocity;
    AnimationType body;
    AnimationType legs;
    unsigned int body_frame;
    unsigned int legs_frame;
    int body_speed;
    int legs_speed;
    bool grounded;
    int direction;
    int fuel;
    unsigned int input_mask;
};

unsigned int InputMask(const Input& input)
{
    // Bits, from low to high: left, right, jump, jets, crouch, prone.
    return static_cast<unsigned int>(input.left) | (static_cast<unsigned int>(input.right) << 1U) |
           (static_cast<unsigned int>(input.jump) << 2U) |
           (static_cast<unsigned int>(input.jets) << 3U) |
           (static_cast<unsigned int>(input.crouch) << 4U) |
           (static_cast<unsigned int>(input.prone) << 5U);
}

void CheckMovement(ScenarioId id, std::span<const MovementCheckpoint> checkpoints)
{
    SCOPED_TRACE(ScenarioIdToString(id));
    ScenarioRunner runner(GetScenario(id));
    runner.RunToCompletion();
    ASSERT_EQ(runner.GetTrace().size(), 180U);
    EXPECT_TRUE(runner.Completed());
    for (const auto& expected : checkpoints) {
        SCOPED_TRACE(::testing::Message() << "tick " << expected.tick);
        const auto& actual = runner.GetTrace().at(expected.tick);
        EXPECT_NEAR(actual.displacement.x, expected.displacement.x, 0.001F);
        EXPECT_NEAR(actual.displacement.y, expected.displacement.y, 0.001F);
        EXPECT_NEAR(actual.velocity.x, expected.velocity.x, 0.00001F);
        EXPECT_NEAR(actual.velocity.y, expected.velocity.y, 0.00001F);
        EXPECT_EQ(actual.body_type, static_cast<int>(expected.body));
        EXPECT_EQ(actual.legs_type, static_cast<int>(expected.legs));
        EXPECT_EQ(actual.body_frame, expected.body_frame);
        EXPECT_EQ(actual.legs_frame, expected.legs_frame);
        EXPECT_EQ(actual.body_speed, expected.body_speed);
        EXPECT_EQ(actual.legs_speed, expected.legs_speed);
        EXPECT_EQ(actual.grounded, expected.grounded);
        EXPECT_EQ(actual.direction, expected.direction);
        EXPECT_EQ(actual.fuel, expected.fuel);
        EXPECT_EQ(InputMask(actual.input), expected.input_mask);
    }
}
